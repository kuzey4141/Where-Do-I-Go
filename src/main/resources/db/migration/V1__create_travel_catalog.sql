CREATE TABLE passport_types (
    code VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    color VARCHAR(30) NOT NULL,
    display_order INTEGER NOT NULL UNIQUE
);

CREATE TABLE countries (
    iso_code VARCHAR(2) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    CONSTRAINT ck_country_iso_code CHECK (
        CHAR_LENGTH(iso_code) = 2 AND iso_code = UPPER(iso_code)
    )
);

CREATE TABLE entry_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_iso_code VARCHAR(2) NOT NULL REFERENCES countries(iso_code),
    passport_type VARCHAR(20) NOT NULL REFERENCES passport_types(code),
    visa_status VARCHAR(30) NOT NULL,
    stay_limit TEXT,
    conditions TEXT,
    source_url VARCHAR(2048),
    fetched_at TIMESTAMP WITH TIME ZONE,
    verified_at DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_entry_rule_country_passport UNIQUE (country_iso_code, passport_type),
    CONSTRAINT ck_entry_rule_visa_status CHECK (visa_status IN (
        'VISA_FREE', 'VISA_REQUIRED', 'E_VISA', 'VISA_ON_ARRIVAL', 'CONDITIONAL', 'UNKNOWN'
    )),
    CONSTRAINT ck_entry_rule_foreign_destination CHECK (country_iso_code <> 'TR'),
    CONSTRAINT ck_entry_rule_verified_source CHECK (
        visa_status = 'UNKNOWN' OR (source_url IS NOT NULL AND verified_at IS NOT NULL)
    )
);

CREATE INDEX idx_entry_rules_passport_status ON entry_rules(passport_type, visa_status);

